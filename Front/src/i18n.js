function translateValidationMessage(value) {
  const attributes = {
    address: 'adresse',
    bedrooms: 'nombre de chambres',
    city: 'ville',
    defects_found: 'défauts constatés',
    description: 'description',
    email: 'adresse e-mail',
    furnishing_status: 'état d’ameublement',
    governorate: 'gouvernorat',
    monthly_rent_tnd: 'loyer mensuel',
    name: 'nom',
    notes: 'notes',
    password: 'mot de passe',
    password_confirmation: 'confirmation du mot de passe',
    phone: 'numéro de téléphone',
    photos: 'photos',
    recommendation: 'recommandation',
    role: 'rôle',
    title: 'titre',
  };
  const labelFor = (attribute) => {
    const baseAttribute = attribute.replace(/\.\d+$/, '');
    return attributes[baseAttribute] ?? baseAttribute.replaceAll('_', ' ');
  };
  let match = value.match(/^The ([\w.]+) field is required\.$/);
  if (match) return `Le champ ${labelFor(match[1])} est obligatoire.`;

  match = value.match(/^The ([\w.]+) must be a valid email address\.$/);
  if (match) return `Le champ ${labelFor(match[1])} doit être une adresse e-mail valide.`;

  match = value.match(/^The ([\w.]+) has already been taken\.$/);
  if (match) return `Cette valeur pour ${labelFor(match[1])} est déjà utilisée.`;

  match = value.match(/^The ([\w.]+) confirmation does not match\.$/);
  if (match) return `La confirmation de ${labelFor(match[1])} ne correspond pas.`;

  match = value.match(/^The ([\w.]+) must be at least (\d+) characters\.$/);
  if (match) return `Le champ ${labelFor(match[1])} doit contenir au moins ${match[2]} caractères.`;

  match = value.match(/^The ([\w.]+) must not be greater than (\d+)\.$/);
  if (match) return `Le champ ${labelFor(match[1])} ne doit pas dépasser ${match[2]}.`;

  return null;
}

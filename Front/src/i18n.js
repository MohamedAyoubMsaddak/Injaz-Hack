let currentLanguage = 'en';

export function setLanguage(language) {
  currentLanguage = language === 'fr' ? 'fr' : 'en';
  try {
    localStorage.setItem('sakani-language', currentLanguage);
  } catch {
    // Language remains available for the current page even if storage is disabled.
  }
}

export function getLanguage() {
  try {
    currentLanguage = localStorage.getItem('sakani-language') === 'fr' ? 'fr' : 'en';
  } catch {
    currentLanguage = 'en';
  }
  return currentLanguage;
}

export function t(value) {
  if (typeof value !== 'string' || currentLanguage !== 'fr') return value;

  const leading = value.match(/^\s*/)?.[0] ?? '';
  const trailing = value.match(/\s*$/)?.[0] ?? '';
  const key = value.trim().replace(/\s+/g, ' ');
  const translated = translations[key] ?? translateStatus(key);

  return translated === key ? value : `${leading}${translated}${trailing}`;
}

